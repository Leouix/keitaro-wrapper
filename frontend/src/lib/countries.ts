const BY_CODE = new Map(COUNTRIES.map((c) => [c.code, c]));

/** 'kz' → { code: 'KZ', name: 'Kazakhstan' }; unknown code → null. */
export function findCountry(raw: string): Country | null {
  const code = raw.trim().toUpperCase();
  return BY_CODE.get(code) ?? null;
}

/** Free-form input: 'KZ, uz  RU' → ['KZ', 'UZ', 'RU'] (no duplicates, order kept). */
export function parseCountryCodes(raw: string): string[] {
  return raw
    .split(/[\s,;]+/)
    .map((part) => part.trim().toUpperCase())
    .filter((part) => part.length > 0)
    .filter((code, i, all) => all.indexOf(code) === i);
}

export function countryName(code: string): string {
  return BY_CODE.get(code)?.name ?? code;
}